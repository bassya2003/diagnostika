function allVecNames(){ return Object.keys(VECTORS).concat(S.customVecs); }

function renderVecs(){
  const g=document.getElementById("vecgrid");
  g.innerHTML=allVecNames().map(v=>{
    const on=S.vecs.includes(v);
    return '<label class="vec '+(on?'on':'')+'"><input type="checkbox" '+(on?'checked':'')+
      ' onchange="toggleVec('+JSON.stringify(v).replace(/"/g,'&quot;')+')"><span>'+v+'</span></label>';
  }).join("");
  const w=document.getElementById("vecwarn");
  if(S.vecs.length>4){ w.style.display="block"; w.textContent="Выбрано "+S.vecs.length+" векторов. Рекомендуем не более 4-х."; }
  else w.style.display="none";
  renderMain(); renderProfs();
}
function toggleVec(v){
  const i=S.vecs.indexOf(v);
  if(i<0){ S.vecs.push(v); if(!S.profs[v]) S.profs[v]=[]; }
  else { S.vecs.splice(i,1); if(S.mainVec===v) S.mainVec=""; }
  renderVecs();
}
function addVec(){
  const el=document.getElementById("newvec"), v=el.value.trim();
  if(!v) return;
  if(allVecNames().includes(v)){ alert("Такой вектор уже есть в списке."); return; }
  S.customVecs.push(v); VECTORS[v]=VECTORS[v]||[];
  el.value=""; S.vecs.push(v); S.profs[v]=[]; renderVecs();
}
function renderMain(){
  const el=document.getElementById("mainvec");
  if(!S.vecs.length){ el.innerHTML='<span class="hint">Сначала выберите вектора выше.</span>'; return; }
  el.innerHTML=S.vecs.map(v=>'<div class="chip '+(S.mainVec===v?'on':'')+'" onclick="setMain('+
    JSON.stringify(v).replace(/"/g,'&quot;')+')">'+v+'</div>').join("");
}
function setMain(v){ S.mainVec=(S.mainVec===v?"":v); renderMain(); }

function renderProfs(){
  const el=document.getElementById("profs");
  if(!S.vecs.length){ el.innerHTML='<p class="hint">Сначала выберите профессиональные вектора.</p>'; return; }
  el.innerHTML=S.vecs.map((v,vi)=>{
    const list=VECTORS[v]||[];
    const chosen=S.profs[v]||[];
    const items=list.map((p,pi)=>{
      const on=chosen.some(c=>c.n===p[0]);
      return '<label class="prof"><input type="checkbox" '+(on?'checked':'')+
        ' onchange="toggleProf('+vi+','+pi+')"><span><b>'+p[0]+'</b><span>'+p[1]+'</span></span></label>';
    }).join("");
    const custom=chosen.filter(c=>c.custom).map((c,ci)=>
      '<div class="eduitem"><div class="row"><div><label class="f">Своя профессия</label>'+
      '<input type="text" value="'+esc(c.n)+'" oninput="editCustom('+vi+','+ci+',\'n\',this.value)"></div>'+
      '<div><label class="f">Описание</label>'+
      '<input type="text" value="'+esc(c.d)+'" oninput="editCustom('+vi+','+ci+',\'d\',this.value)"></div></div>'+
      '<button class="del" onclick="delCustom('+vi+','+ci+')">Удалить</button></div>').join("");
    return '<div class="vecblock"><h3>'+v+'</h3>'+
      '<p class="hint">Выбрано: '+chosen.length+' (рекомендуем не более 3-х)</p>'+
      items+custom+
      '<button class="btn ghost sm" style="margin-top:8px" onclick="addCustomProf('+vi+')">+ Другая профессия</button></div>';
  }).join("");
}
function toggleProf(vi,pi){
  const v=S.vecs[vi], p=VECTORS[v][pi];
  S.profs[v]=S.profs[v]||[];
  const i=S.profs[v].findIndex(c=>c.n===p[0]);
  if(i<0) S.profs[v].push({n:p[0],d:p[1]}); else S.profs[v].splice(i,1);
  renderProfs();
}
function addCustomProf(vi){
  const v=S.vecs[vi]; S.profs[v]=S.profs[v]||[];
  S.profs[v].push({n:"",d:"",custom:true}); renderProfs();
}
function editCustom(vi,ci,field,val){
  const v=S.vecs[vi]; const cs=S.profs[v].filter(c=>c.custom);
  if(cs[ci]) cs[ci][field]=val;
}
function delCustom(vi,ci){
  const v=S.vecs[vi]; const cs=S.profs[v].filter(c=>c.custom);
  const target=cs[ci]; S.profs[v]=S.profs[v].filter(c=>c!==target); renderProfs();
}

